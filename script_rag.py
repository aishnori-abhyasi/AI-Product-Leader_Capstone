# 3. READABILITY  (Flesch Reading Ease + Flesch-Kincaid Grade, no dependencies)
# ─────────────────────────────────────────────────────────────────────────────
def count_syllables(word: str) -> int:
    w = re.sub(r"[^a-z]", "", word.lower())
    if not w:
        return 0
    if len(w) <= 3:
        return 1
    w = re.sub(r"(?:[^laeiouy]es|ed|[^laeiouy]e)$", "", w)
    w = re.sub(r"^y", "", w)
    return max(1, len(re.findall(r"[aeiouy]{1,2}", w)))

def split_sentences(text: str):
    parts = re.split(r"(?<=[.!?])\s+|\n+", text.strip())
    return [p for p in parts if re.search(r"[A-Za-z0-9]", p)]

def readability(text: str) -> dict:
    sents = split_sentences(text)
    words = re.findall(r"[A-Za-z][A-Za-z'-]*", text)
    if not sents or not words:
        return {"grade": 0.0, "ease": 100.0, "words": 0, "sentences": 0,
                "avg_sentence_len": 0, "long_sentences": []}
    syl = sum(count_syllables(w) for w in words)
    wps, spw = len(words) / len(sents), syl / len(words)
    return {
        "grade": round(0.39 * wps + 11.8 * spw - 15.59, 1),    # Flesch-Kincaid Grade
        "ease": round(206.835 - 1.015 * wps - 84.6 * spw, 1),   # Flesch Reading Ease
        "words": len(words), "sentences": len(sents),
        "avg_sentence_len": round(wps, 1),
        "long_sentences": [s for s in sents if len(s.split()) > 18],
    }

