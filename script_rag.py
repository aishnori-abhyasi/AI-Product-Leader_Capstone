# 5. GROUNDING GUARD  (numbers are where finance copy goes wrong)
# ─────────────────────────────────────────────────────────────────────────────
NUM = re.compile(r"\d[\d,]*")
def _nums(s):                                   # "15,000" and "15000" are equal
    return {n.replace(",", "") for n in NUM.findall(s)}

def grounding_check(script, facts):
    allowed = set().union(*[_nums(f["text"]) for f in facts]) if facts else set()
    extra = _nums(script) - allowed
    return {"ok": not extra, "unsupported_numbers": sorted(extra)}

def meaning_guard(script, facts):
    """Readability can improve while meaning breaks. Check what must survive."""
    missing = [p for f in facts for p in f.get("must_keep", [])
               if not re.search(p, script, re.I)]
    sents = split_sentences(script)
    fragments = [s for s in sents if len(s.split()) < 4 and not PROTECT.search(s)]
    lower_start = [s for s in sents if s[:1].islower()]
    dup = re.findall(r"\b(\w+ \w+) (?:at|to) \1\b", script, re.I)   # e.g. "sign up at sign up"
    return {"ok": not (missing or fragments or lower_start or dup),
            "missing_must_keep": missing, "fragments": fragments,
            "lowercase_starts": lower_start, "stutters": dup}

