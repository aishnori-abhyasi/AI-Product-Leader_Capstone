# 2. RETRIEVER  (hard metadata filter first, then semantic ranking)
# ─────────────────────────────────────────────────────────────────────────────
class SchemeRetriever:
    def __init__(self, kb, verified_only=False):
        self.kb = [d for d in kb if d["verified"]] if verified_only else list(kb)
        self.vec = TfidfVectorizer(ngram_range=(1, 2), stop_words="english")
        self.matrix = self.vec.fit_transform(
            [d["name"] + ". " + d["text"] for d in self.kb])

    def search(self, query, tier, has_bank_account, occupation="", k=3, kinds=None):
        # hard eligibility rules are applied BEFORE similarity, never after
        def occ_ok(d):
            req = d.get("occupations")
            return not req or any(r in occupation.lower() for r in req)
        idx = [i for i, d in enumerate(self.kb)
               if tier in d["tiers"] and occ_ok(d)
               and (has_bank_account or not d["needs_bank_account"])
               and (not kinds or d["kind"] in kinds)]      # policy decides WHICH kinds
        if not idx:
            return []
        sims = cosine_similarity(self.vec.transform([query]), self.matrix[idx]).ravel()
        ranked = [idx[i] for i in sims.argsort()[::-1]]
        if not kinds:
            return [self.kb[i] for i in ranked[:k]]
        picked = []                                         # best match per kind, in policy order
        for kind in kinds:
            for i in ranked:
                if self.kb[i]["kind"] == kind and i not in picked:
                    picked.append(i); break
        picked += [i for i in ranked if i not in picked]
        return [self.kb[i] for i in picked[:k]]

