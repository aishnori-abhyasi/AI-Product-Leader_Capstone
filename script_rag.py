def _claude(prompt: str) -> str | None:
    if not os.getenv("ANTHROPIC_API_KEY"):
        return None
    try:
        import anthropic
        client = anthropic.Anthropic()
        msg = client.messages.create(
            model=os.getenv("CLAUDE_MODEL", "claude-sonnet-4-6"),
            max_tokens=700, system=SYSTEM,
            messages=[{"role": "user", "content": prompt}])
        return msg.content[0].text.strip()
    except Exception as e:                       # fall back to offline path
        print("  [claude unavailable, using offline rewriter]", e)
        return None

def draft_script(profile, facts) -> str:
    fact_block = "\n".join(f"- {f['name']}: {f['text']}" for f in facts)
    prompt = (f"Person profile: segment='{profile['segment']}', score band='{profile['band']}'.\n"
              f"FACTS:\n{fact_block}\n\n"
              "Write a 60-90 word script that tells the person what to do first and "
              "what they could apply for.")
    out = _claude(prompt)
    if out:
        return out
    # offline draft: deliberately "bank-speak" so the optimiser has work to do
    lines = ["Based on your UPI activity over the past 90 days, here are some options for you."]
    lines += [f["text"] for f in facts]
    return " ".join(lines)

def rewrite_script(script, report, facts, round_no) -> str:
    prompt = (f"Rewrite this script. It scored Flesch-Kincaid grade {report['grade']} and "
              f"reading ease {report['ease']}. Target: grade 6 or lower, ease 70 or higher.\n"
              f"Average sentence length is {report['avg_sentence_len']} words; keep it under 12.\n"
              f"Long sentences to fix:\n- " + "\n- ".join(report["long_sentences"][:5]) +
              "\n\nFACTS you may use:\n" + "\n".join(f"- {f['text']}" for f in facts) +
              f"\n\nSCRIPT:\n{script}\n\nReturn only the new script.")
    out = _claude(prompt)
    if out:
        return out
    return offline_simplify(script, aggressive=round_no >= 2)

def _cap(t):                                   # capitalise first letter only
    t = t.strip()
    return t[:1].upper() + t[1:]

def offline_simplify(text: str, aggressive=False) -> str:
    """Test-harness rewriter. Deliberately conservative: it will NOT hit grade 6 on
    every input - that is the job of the LLM rewriter. Its main purpose is to let
    the loop, scoring and guards run without an API key."""
    # protect URLs/domains from word swaps and sentence splitting
    keep = {}
    def hold(m):
        k = f"URLX{len(keep)}X"; keep[k] = m.group(0); return k
    text = PROTECT.sub(hold, text)
    for pat, rep in PHRASES:
        text = re.sub(pat, rep, text, flags=re.I)
    for k, v in JARGON.items():
        text = re.sub(rf"\b{k}\b", v, text, flags=re.I)
    limit = 11 if aggressive else 15
    out = []
    for s in split_sentences(text):
        if len(s.split()) > limit:
            parts = re.split(r";\s+|,\s+(?:and|but|so)\s+|,\s+(?:if|when|because)\s+", s)
            merged = []
            for p in parts:                    # never leave tiny fragments
                if merged and len(p.split()) < 5:
                    merged[-1] += ", " + p
                else:
                    merged.append(p)
            out += [_cap(p).rstrip(".") + "." for p in merged if p.strip()]
        else:
            out.append(_cap(s) if s.endswith((".", "!", "?")) else _cap(s) + ".")
    text = " ".join(out)
    for k, v in keep.items():
        text = text.replace(k, v)
    return text

