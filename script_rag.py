# 6. THE LOOP
# ─────────────────────────────────────────────────────────────────────────────
@dataclass
class Result:
    script: str
    history: list = field(default_factory=list)
    facts: list = field(default_factory=list)
    grounded: dict = field(default_factory=dict)
    meaning: dict = field(default_factory=dict)
    passed: bool = False                 # readability target met
    safe_to_ship: bool = False           # readability + grounding + meaning + verified facts

def profile_to_query(profile) -> str:
    q = {"A": "bank account first steps registration free",
         "B": "small loan no collateral first loan registration insurance",
         "C": "loan savings pension insurance grow business",
         "D": "pension savings insurance long term"}[profile["tier"]]
    return q + " " + profile.get("occupation", "")

def optimise(profile, retriever, target_grade=6.0, min_ease=70.0, max_rounds=4) -> Result:
    facts = retriever.search(profile_to_query(profile), profile["tier"],
                             profile["has_bank_account"],
                             occupation=profile.get("occupation", ""), k=3,
                             kinds=profile.get("lead_with"))
    script = draft_script(profile, facts)
    res = Result(script=script, facts=facts)
    for r in range(max_rounds + 1):
        rep = readability(script)
        res.history.append({"round": r, "grade": rep["grade"], "ease": rep["ease"],
                            "avg_sentence_len": rep["avg_sentence_len"], "text": script})
        if rep["grade"] <= target_grade and rep["ease"] >= min_ease:
            res.passed = True
            break
        if r == max_rounds:
            break
        new = rewrite_script(script, rep, facts, r)
        if new.strip() == script.strip():          # rewriter is stuck: stop, flag for a human/LLM
            res.history.append({"round": r + 1, "note": "plateau - no further change"})
            break
        script = new
    res.script = script
    res.grounded = grounding_check(script, facts)
    res.meaning = meaning_guard(script, facts)
    res.safe_to_ship = (res.passed and res.grounded["ok"] and res.meaning["ok"]
                        and all(f["verified"] for f in facts))
    return res

